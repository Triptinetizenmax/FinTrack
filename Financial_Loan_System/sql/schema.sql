-- Compatible with the existing financial_loan_db and customers/loan_applications tables.
CREATE TABLE IF NOT EXISTS customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    income NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (income >= 0)
);

ALTER TABLE customers ADD COLUMN IF NOT EXISTS date_of_birth DATE;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS phone VARCHAR(20);
ALTER TABLE customers ADD COLUMN IF NOT EXISTS email VARCHAR(150);
ALTER TABLE customers ADD COLUMN IF NOT EXISTS address TEXT;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'customers'
      AND column_name = 'customer_id' AND is_identity = 'YES'
  ) THEN
    ALTER TABLE customers ALTER COLUMN customer_id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS loan_applications (
    application_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
    loan_amount NUMERIC(12,2) NOT NULL CHECK (loan_amount > 0),
    loan_purpose VARCHAR(100) NOT NULL,
    application_status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (application_status IN ('Pending','Approved','Rejected')),
    application_date DATE NOT NULL DEFAULT CURRENT_DATE,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

