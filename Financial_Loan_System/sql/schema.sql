ALTER TABLE loan_applications ADD COLUMN IF NOT EXISTS application_date DATE DEFAULT CURRENT_DATE;
ALTER TABLE loan_applications ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Synchronize identity sequences with existing manually inserted IDs.
DO $$
DECLARE seq_name TEXT; max_id BIGINT;
BEGIN
  SELECT pg_get_serial_sequence('loan_applications','application_id') INTO seq_name;
  SELECT COALESCE(MAX(application_id), 0) INTO max_id FROM loan_applications;
  IF seq_name IS NOT NULL AND max_id > 0 THEN PERFORM setval(seq_name, max_id, true); END IF;
  SELECT pg_get_serial_sequence('customers','customer_id') INTO seq_name;
  SELECT COALESCE(MAX(customer_id), 0) INTO max_id FROM customers;
  IF seq_name IS NOT NULL AND max_id > 0 THEN PERFORM setval(seq_name, max_id, true); END IF;
END $$;

CREATE TABLE IF NOT EXISTS loans (
    loan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id INTEGER NOT NULL UNIQUE REFERENCES loan_applications(application_id),
    principal NUMERIC(12,2) NOT NULL CHECK (principal > 0),
    annual_interest_rate NUMERIC(5,2) NOT NULL CHECK (annual_interest_rate >= 0),
    tenure_months INTEGER NOT NULL CHECK (tenure_months > 0),
    emi_amount NUMERIC(12,2) NOT NULL CHECK (emi_amount > 0),
    outstanding_balance NUMERIC(12,2) NOT NULL CHECK (outstanding_balance >= 0),
    disbursed_on DATE NOT NULL DEFAULT CURRENT_DATE,
    loan_status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (loan_status IN ('Active','Closed')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS emi_schedule (
    emi_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id INTEGER NOT NULL REFERENCES loans(loan_id) ON DELETE CASCADE,
    installment_number INTEGER NOT NULL,
    due_date DATE NOT NULL,
    emi_amount NUMERIC(12,2) NOT NULL CHECK (emi_amount > 0),
    principal_component NUMERIC(12,2) NOT NULL DEFAULT 0,
    interest_component NUMERIC(12,2) NOT NULL DEFAULT 0,
    amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Due' CHECK (status IN ('Due','Partial','Paid','Overdue')),
    UNIQUE (loan_id, installment_number)
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emi_id INTEGER NOT NULL REFERENCES emi_schedule(emi_id),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_method VARCHAR(30) NOT NULL DEFAULT 'Manual',
    reference_note VARCHAR(150)
);

CREATE INDEX IF NOT EXISTS idx_applications_customer ON loan_applications(customer_id);
CREATE INDEX IF NOT EXISTS idx_applications_status ON loan_applications(application_status);
CREATE INDEX IF NOT EXISTS idx_emi_due_date ON emi_schedule(due_date, status);
